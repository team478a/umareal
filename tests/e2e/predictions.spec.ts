test.afterAll(() => db.$disconnect());
test('publishes a reviewed prediction, requires correction approval, and preserves both public versions', async ({ page, context }, testInfo) => {
  const fixture = await assessmentFixture();
  await context.addCookies([{ name: 'keiba_session', value: fixture.token, domain: 'localhost', path: '/', httpOnly: true, sameSite: 'Lax' }]);
  await page.goto('/expert');
  const row = page.locator('.race-row').filter({ hasText: fixture.race.name }); await row.getByRole('button', { name: '評価を入力' }).click();
  await page.getByRole('button', { name: '最終予想・公開へ' }).click();
  await page.getByLabel('公開範囲', { exact: true }).selectOption('FREE');
  await page.getByLabel('信頼度', { exact: true }).selectOption('A');
  await page.getByLabel('勝負判断', { exact: true }).selectOption('NORMAL');
  await page.getByLabel('総評', { exact: true }).fill('画面試験の最終予想です。');
  await page.getByLabel('1番の最終印', { exact: true }).selectOption('HONMEI');
  await page.getByLabel('1番の印の理由', { exact: true }).fill('軸として評価');
  await page.getByLabel('2番の最終印', { exact: true }).selectOption('TAIKO');
  await page.getByLabel('参考買い目', { exact: true }).fill('EXACTA,1-2/2-1,500');
  await expect(page.locator('.prediction-total')).toContainText('1,000円');
  await page.getByRole('button', { name: '公開前に確認' }).click();
  await expect(page.getByRole('heading', { name: '初版 1の公開前確認' })).toBeVisible();
  await expect(page.locator('.publish-preview').getByRole('alert')).toContainText('パドック未入力');
  expect(await db.predictionVersion.count({ where: { prediction: { raceId: fixture.race.id } } })).toBe(0);
  await page.getByRole('button', { name: '最終予想を公開する' }).click();
  await expect(page.getByText('公開版1を保存しました。', { exact: true })).toBeVisible();
  const first = await db.predictionVersion.findFirstOrThrow({ where: { prediction: { raceId: fixture.race.id } } });
  expect(await db.notificationEvent.count({ where: { versionId: first.id, status: 'QUEUED' } })).toBe(1);
  await page.getByLabel('公開範囲', { exact: true }).selectOption('PAID');
  await page.getByLabel('総評', { exact: true }).fill('訂正版の総評です。');
  await page.getByLabel('訂正理由', { exact: true }).fill('総評の表現を訂正');
  await page.getByRole('button', { name: '公開前に確認' }).click();
  await expect(page.locator('.prediction-editor .notice.error')).toContainText('管理者の確認が必要');
  const admin = await assessmentFixture('ADMIN'); await context.clearCookies();
  await context.addCookies([{ name: 'keiba_session', value: admin.token, domain: 'localhost', path: '/', httpOnly: true, sameSite: 'Lax' }]);
  await page.getByRole('button', { name: '公開前に確認' }).click();
  await expect(page.getByRole('heading', { name: '訂正版 2の公開前確認' })).toBeVisible();
  await page.getByRole('button', { name: '訂正版を公開する' }).click();
  await expect(page.getByText('公開版2を保存しました。', { exact: true })).toBeVisible();
  expect(await db.predictionVersion.count({ where: { prediction: { raceId: fixture.race.id } } })).toBe(2);
  await context.clearCookies(); await page.goto(`/races/${fixture.race.id}`);
  await expect(page.getByRole('heading', { name: '有料会員向けの最終予想です' })).toBeVisible();
  await expect(page.getByText('訂正版の総評です。', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '版1' }).click();
  await expect(page.getByRole('heading', { name: '最終予想 · 版1' })).toBeVisible();
  await expect(page.getByText('画面試験の最終予想です。', { exact: true })).toBeVisible();
  await context.addCookies([{ name: 'keiba_session', value: admin.token, domain: 'localhost', path: '/', httpOnly: true, sameSite: 'Lax' }]); await page.reload();
  await expect(page.getByRole('heading', { name: '最終予想 · 版2' })).toBeVisible();
  await expect(page.getByText('訂正版の総評です。', { exact: true })).toBeVisible();
  await expect(page.getByText('訂正理由：総評の表現を訂正', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('published-prediction.png'), fullPage: true });
  await db.race.update({ where: { id: fixture.race.id }, data: { startsAt: new Date(Date.now() - 60_000) } });
  await page.goto('/admin/results');
  const resultRow = page.getByRole('button').filter({ hasText: fixture.race.name }); await resultRow.click();
  await page.getByLabel('1番の着順').fill('1'); await page.getByLabel('2番の着順').fill('2');
  await page.getByLabel('払戻CSV').fill('EXACTA,1-2,640,PAYOUT');
  await page.getByLabel('結果の確認理由').fill('画面試験で公式結果を確認');
  await page.getByRole('button', { name: '結果を確定' }).click();
  await expect(page.getByText('確定結果版1と公開版別成績を保存しました。')).toBeVisible();
  await page.goto(`/races/${fixture.race.id}`);
  await expect(page.getByRole('heading', { name: '確定結果' })).toBeVisible();
  await expect(page.getByText('公開版2 · 的中')).toBeVisible();
  await page.goto('/results'); await expect(page.getByRole('heading', { name: '予想成績' })).toBeVisible();
});
test('completes all 18 paddock entries and a formal skip inside the three-minute interaction budget', async ({ page, context }) => {
  const fixture = await assessmentFixture('EXPERT', 2, 18); const startedAt = Date.now();
  await context.addCookies([{ name: 'keiba_session', value: fixture.token, domain: 'localhost', path: '/', httpOnly: true, sameSite: 'Lax' }]);
  await page.goto('/expert'); const row = page.locator('.race-row').filter({ hasText: fixture.race.name }); await row.getByRole('button', { name: '評価を入力' }).click();
  for (let number = 1; number <= 18; number++) {
    for (const label of ['馬体の張り', '歩様・踏み込み', '毛艶', '気合・集中力', '発汗・落ち着き']) await page.getByRole('button', { name: `${label} 3`, exact: true }).click();
    await page.getByRole('button', { name: '据え置き', exact: true }).click();
    if (number < 18) await page.getByRole('button', { name: '次の馬', exact: true }).click();
  }
  await expect(page.locator('.assessment-progress')).toContainText('パドック入力 18 / 18頭');
  await expect(page.locator('.assessment-progress [role=status]')).toHaveText('保存済み');
  await page.getByRole('button', { name: '最終予想・公開へ' }).click();
  await page.getByLabel('公開範囲', { exact: true }).selectOption('FREE'); await page.getByLabel('信頼度', { exact: true }).selectOption('B'); await page.getByLabel('勝負判断', { exact: true }).selectOption('SKIP');
  await page.getByLabel('総評', { exact: true }).fill('全頭を確認しましたが、今回は正式に見送ります。');
  await page.getByRole('button', { name: '公開前に確認' }).click(); await expect(page.getByText('見送り（買い目なし）', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '最終予想を公開する' }).click(); await expect(page.getByText('公開版1を保存しました。', { exact: true })).toBeVisible();
  expect(Date.now() - startedAt).toBeLessThan(180_000);
  const version = await db.predictionVersion.findFirstOrThrow({ where: { prediction: { raceId: fixture.race.id } }, include: { bets: true } });
  expect(version.stance).toBe('SKIP'); expect(version.estimatedTotalYen).toBe(0); expect(version.bets).toHaveLength(0);
});
