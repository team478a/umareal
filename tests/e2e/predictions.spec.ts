test('selects paddock horses with circles and publishes the reviewed quick bulletin', async ({ page, context }) => {
  const fixture = await assessmentFixture();
  await context.addCookies([{ name: 'keiba_session', value: fixture.token, domain: 'localhost', path: '/', httpOnly: true, sameSite: 'Lax' }]);
  await page.goto('/expert');
  await page.locator('.race-row').filter({ hasText: fixture.race.name }).getByRole('button', { name: '評価・予想を入力' }).click();
  const quick = page.locator('.quick-paddock');
  await quick.getByRole('button', { name: `1番 ${fixture.entries[0].horseName}`, exact: true }).click();
  await quick.getByRole('button', { name: `2番 ${fixture.entries[1].horseName}`, exact: true }).click();
  await expect(quick.getByRole('button', { name: `1番 ${fixture.entries[0].horseName} 選択済み`, exact: true })).toHaveAttribute('aria-pressed', 'true');
  await quick.getByRole('button', { name: 'A', exact: true }).click();
  await quick.getByRole('button', { name: '選択した2頭の配信内容を確認', exact: true }).click();
  await expect(quick.getByRole('heading', { name: '初版 1の配信前確認' })).toBeVisible();
  await expect(quick).toContainText(`○ 1番 ${fixture.entries[0].horseName}`);
  await expect(quick).toContainText(`○ 2番 ${fixture.entries[1].horseName}`);
  await quick.getByRole('button', { name: 'この内容で確定・公開', exact: true }).click();
  await expect(page.getByText('公開版1を保存しました。', { exact: true })).toBeVisible();
  const version = await db.predictionVersion.findFirstOrThrow({ where: { prediction: { raceId: fixture.race.id } }, include: { marks: true } });
  expect(version.formatVersion).toBe('HORSE_EVALUATION_V1'); expect(version.contentSnapshot).toMatchObject({ mode: 'QUICK_PICK' });
  expect(version.marks).toHaveLength(2); expect(version.marks.every(mark => mark.mark === 'TAIKO')).toBe(true);
  await page.goto(`/races/${fixture.race.id}`);
  await expect(page.getByRole('heading', { name: 'パドック速報 · 版1' })).toBeVisible();
  await expect(page.getByRole('heading', { name: '○ パドック注目馬' })).toBeVisible();
  await expect(page.getByText('○ 注目馬', { exact: true })).toHaveCount(2);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
